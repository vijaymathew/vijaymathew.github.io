def chips(tags, blog, counts=None):
    """Tag links. ``blog`` is the relative path from the page to the blog."""
    if not tags:
        return ""
    return '<span class="chips">' + "".join(
        f'<a class="chip" href="{blog}tags/{slugify(t)}.html">{E(t)}'
        + (f" <i>{counts[t]}</i>" if counts else "") + "</a>"
        for t in tags) + "</span>"


def post_item(p, blog, date_format="%-d %b"):
    summary = f"\n      <p>{E(p['summary'])}</p>" if p["summary"] else ""
    return f"""  <article class="post-item">
    <time datetime="{p['date'].isoformat()}">{p['date'].strftime(date_format)}</time>
    <div>
      <h3><a href="{blog}{p['slug']}.html">{E(p['title'])}</a></h3>{summary}
      {chips(p['tags'], blog)}
    </div>
  </article>
"""


def comments(p):
    if GISCUS["enabled"]:
        return f"""  <section class="comments" id="comments">
    <h2>Comments</h2>
    <div class="giscus" data-repo="{REPO}" data-repo-id="{GISCUS['repo_id']}" data-category="{E(GISCUS['category'])}" data-category-id="{GISCUS['category_id']}" data-mapping="pathname" data-strict="1" data-reactions-enabled="1" data-emit-metadata="0" data-input-position="top" data-lang="en" data-loading="lazy"></div>
    <noscript><p>Comments are on <a href="https://github.com/{REPO}/discussions">GitHub Discussions</a>.</p></noscript>
  </section>
"""
    new = f"https://github.com/{REPO}/discussions/new?category=general&title={quote(p['title'])}"
    return f"""  <section class="comments" id="comments">
    <h2>Comments</h2>
    <p>Questions, corrections, a better way to do it? <a href="{new}" target="_blank" rel="noopener">Start a discussion on GitHub →</a></p>
  </section>
"""


# ── pages ────────────────────────────────────────────────────────────────────

def post_page(p, newer, older):
    head = (f'  <meta property="og:type" content="article">\n'
            f'  <meta property="article:published_time" content="{p["date"].isoformat()}">\n'
            + "".join(f'  <meta property="article:tag" content="{E(t)}">\n' for t in p["tags"]))
    lead = f'\n    <p class="lead">{E(p["summary"])}</p>' if p["summary"] else ""
    cards = "".join(
        f'    <a class="next-card" href="./{q["slug"]}.html"><small>{label}</small><b>{E(q["title"])}</b>'
        f'<span>{q["date"].strftime("%-d %B %Y")}</span></a>\n'
        for label, q in (("newer", newer), ("older", older)) if q)
    cards += '    <a class="next-card" href="./index.html"><small>blog</small><b>All posts</b><span>Everything, newest first.</span></a>\n'
    body = f"""  <header class="page-head post-head">
    <span class="eyebrow">// blog</span>
    <h1>{E(p['title'])}</h1>{lead}
    <p class="post-meta"><time datetime="{p['date'].isoformat()}">{p['date'].strftime("%-d %B %Y")}</time><span>{p['minutes']} min read</span>{chips(p['tags'], "./")}</p>
  </header>

  <article class="article prose post">
{p['body']}
  </article>

  <div class="post-foot">
  <div class="next-cards">
    <h2>Keep reading</h2>
{cards}  </div>
{comments(p)}  </div>"""
    return page(root="../", title=f"{p['title']} — Nex", desc=p["summary"] or BLOG_DESC,
                url=f"{BLOG_URL}{p['slug']}.html", body=body, head=head)


def index_page(posts, counts):
    out, year = "", None
    for p in posts:
        if p["date"].year != year:
            year = p["date"].year
            out += f'  <h2 class="year-h">{year}</h2>\n'
        out += post_item(p, "./")
    if not posts:
        out = '  <p class="blurb">Nothing here yet.</p>\n'
    tags = sorted(counts, key=lambda t: (-counts[t], t.lower()))
    bar = (f'  <p class="tag-bar">{chips(tags, "./", counts)}<a class="more" href="./tags/index.html">All tags →</a></p>\n'
           if tags else "")
    body = f"""  <header class="page-head">
    <span class="eyebrow">// blog</span>
    <h1>{E(BLOG_TITLE)}</h1>
    <p class="lead">{E(BLOG_DESC)} <a href="./feed.xml">Subscribe to the feed</a>.</p>
  </header>

  <div class="posts">
{bar}{out}  </div>"""
    return page(root="../", title=f"{BLOG_TITLE}", desc=BLOG_DESC, url=BLOG_URL, body=body,
                head='  <meta property="og:type" content="website">\n')


def tag_page(tag, posts):
    n = len(posts)
    body = f"""  <header class="page-head">
    <span class="eyebrow">// tag</span>
    <h1>{E(tag)}</h1>
    <p class="lead">{n} post{"" if n == 1 else "s"}, newest first. <a href="./index.html">All tags</a> · <a href="../index.html">All posts</a></p>
  </header>

  <div class="posts">
{"".join(post_item(p, "../", "%-d %b %Y") for p in posts)}  </div>"""
    return page(root="../../", title=f"Posts tagged {tag} — Nex", desc=f"Nex blog posts tagged {tag}.",
                url=f"{BLOG_URL}tags/{slugify(tag)}.html", body=body)


def tags_page(by_tag):
    out = ""
    for tag in sorted(by_tag, key=str.lower):
        rows = "".join(
            f'    <li><time datetime="{p["date"].isoformat()}">{p["date"].strftime("%-d %b %Y")}</time>'
            f'<a href="../{p["slug"]}.html">{E(p["title"])}</a></li>\n' for p in by_tag[tag])
        out += (f'  <h2 class="year-h" id="{slugify(tag)}"><a href="./{slugify(tag)}.html">{E(tag)}</a>'
                f' <i>{len(by_tag[tag])}</i></h2>\n  <ul class="tag-posts">\n{rows}  </ul>\n')
    body = f"""  <header class="page-head">
    <span class="eyebrow">// blog</span>
    <h1>Tags</h1>
    <p class="lead">Every post, grouped by tag. <a href="../index.html">All posts by date</a></p>
  </header>

  <div class="posts">
{out}  </div>"""
    return page(root="../../", title="Tags — The Nex Blog", desc="Nex blog posts grouped by tag.",
                url=f"{BLOG_URL}tags/", body=body)


def feed(posts):
    stamp = lambda d: d.isoformat() + "T00:00:00Z"
    entries = "".join(f"""  <entry>
    <title>{E(p['title'])}</title>
    <link href="{BLOG_URL}{p['slug']}.html"/>
    <id>{BLOG_URL}{p['slug']}.html</id>
    <published>{stamp(p['date'])}</published>
    <updated>{stamp(p['updated'])}</updated>
    <summary>{E(p['summary'])}</summary>
{"".join(f'    <category term="{E(t)}"/>' + chr(10) for t in p['tags'])}    <content type="html" xml:base="{BLOG_URL}">{E(p['body'])}</content>
  </entry>
""" for p in posts[:20])
    updated = stamp(max((p["updated"] for p in posts), default=datetime.date(2026, 1, 1)))
    return f"""<?xml version="1.0" encoding="utf-8"?>
<feed xmlns="http://www.w3.org/2005/Atom">
  <title>{E(BLOG_TITLE)}</title>
  <subtitle>{E(BLOG_DESC)}</subtitle>
  <link href="{BLOG_URL}feed.xml" rel="self"/>
  <link href="{BLOG_URL}"/>
  <id>{BLOG_URL}</id>
  <updated>{updated}</updated>
  <author><name>{E(AUTHOR)}</name></author>
{entries}</feed>
"""


def write(rel, text):
    path = os.path.join(HERE, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def main():
    drafts = "--drafts" in sys.argv[1:]
    posts = [load(f) for f in sorted(os.listdir(POSTS)) if f.endswith(".md")]
    posts = [p for p in posts if drafts or not p["draft"]]
    posts.sort(key=lambda p: (p["date"], p["slug"]), reverse=True)

    seen = {"index": "the blog index"}
    for p in posts:
        if p["slug"] in seen:
            die(f"{p['source']}: slug '{p['slug']}' is already used by {seen[p['slug']]}")
        seen[p["slug"]] = p["source"]

    by_tag, names = {}, {}
    for p in posts:
        # Tags that differ only in case or punctuation are one tag.
        p["tags"] = list(dict.fromkeys(names.setdefault(slugify(t), t) for t in p["tags"] if slugify(t)))
        for t in p["tags"]:
            by_tag.setdefault(t, []).append(p)
    if "index" in names:
        die("'index' cannot be used as a tag")
    counts = {t: len(ps) for t, ps in by_tag.items()}

    # Clear the previous build, so a renamed or deleted post leaves nothing behind.
    for old in glob.glob(os.path.join(HERE, "*.html")):
        os.remove(old)
    shutil.rmtree(os.path.join(HERE, "tags"), ignore_errors=True)

    for i, p in enumerate(posts):
        newer = posts[i - 1] if i > 0 else None
        older = posts[i + 1] if i + 1 < len(posts) else None
        write(p["slug"] + ".html", post_page(p, newer, older))
    write("index.html", index_page(posts, counts))
    write("tags/index.html", tags_page(by_tag))
    for tag, tagged in by_tag.items():
        write(f"tags/{slugify(tag)}.html", tag_page(tag, tagged))
    write("feed.xml", feed(posts))
    print(f"blog: {len(posts)} post(s), {len(by_tag)} tag(s)")


if __name__ == "__main__":
    main()
