#!/usr/bin/env python3
"""Static site generator for the Nex blog.

A post is one Markdown file in ``posts/``, named ``YYYY-MM-DD-slug.md``:

    ---
    title: Handling command-line arguments in Nex
    tags: [how-to, cli]
    summary: One or two sentences for the index, the feed and link previews.
    ---

    The body, in Markdown. Fenced code blocks are highlighted as Nex unless
    they name another language or start with "$ ".

Optional front matter: ``date`` (overrides the one in the file name),
``updated``, ``slug``, and ``draft: true`` (built only with ``--drafts``).

Running the script writes, next to it, ``<slug>.html`` for every post,
``index.html`` (newest first, by year), ``tags/`` (a page per tag and an
overview) and ``feed.xml`` (Atom). All of that is build output: it is
git-ignored and regenerated by .github/workflows/pages.yml on every push.

    pip install -r requirements.txt
    python3 build.py [--drafts]
"""
import datetime, glob, html, os, re, shutil, sys
from urllib.parse import quote

import markdown, yaml

HERE  = os.path.dirname(os.path.abspath(__file__))
POSTS = os.path.join(HERE, "posts")

SITE_URL   = "https://schemer.in"
BLOG_URL   = SITE_URL + "/nex/blog/"
BLOG_TITLE = "The Nex Blog"
BLOG_DESC  = "Notes on Nex: how to use it, how it is designed, and what is changing."
AUTHOR     = "Vijay Mathew"
REPO       = "vijaymathew/nex"

# Comments are GitHub Discussions threads, embedded by giscus (https://giscus.app).
# Install the giscus app on REPO, then set "enabled" to True. Until then each
# post ends with a plain link that starts a discussion.
GISCUS = {
    "enabled":     False,
    "repo_id":     "R_kgDORPL8hQ",
    "category":    "Announcements",
    "category_id": "DIC_kwDORPL8hc4DHU-f",
}

FRONT = re.compile(r"\A---\s*\n(.*?)\n---\s*\n(.*)\Z", re.S)
NAME  = re.compile(r"^(\d{4}-\d{2}-\d{2})-(.+)\.md$")
E = html.escape


def die(msg):
    sys.exit("blog: " + msg)


def as_date(value, where):
    if isinstance(value, datetime.datetime):
        return value.date()
    if isinstance(value, datetime.date):
        return value
    try:
        return datetime.date.fromisoformat(str(value))
    except ValueError:
        die(f"{where}: bad date {value!r}, expected YYYY-MM-DD")


def slugify(text):
    return re.sub(r"[^a-z0-9]+", "-", str(text).lower()).strip("-")


def load(fname):
    with open(os.path.join(POSTS, fname), encoding="utf-8") as f:
        m = FRONT.match(f.read())
    if not m:
        die(f"{fname}: no front matter (a '---' block at the top of the file)")
    try:
        meta = yaml.safe_load(m.group(1)) or {}
    except yaml.YAMLError as e:
        die(f"{fname}: front matter is not valid YAML: {e}")
    named = NAME.match(fname)
    if not meta.get("title"):
        die(f"{fname}: front matter needs a title")
    if not (named or meta.get("date")):
        die(f"{fname}: name the file YYYY-MM-DD-slug.md, or give it a date")
    date = as_date(meta.get("date") or named.group(1), fname)
    tags = meta.get("tags") or []
    if isinstance(tags, str):
        tags = [t.strip() for t in tags.split(",")]
    md = markdown.Markdown(
        extensions=["fenced_code", "tables", "footnotes", "attr_list", "toc", "smarty"],
        # "--" is a Nex comment and a command-line flag; never turn it into a dash.
        extension_configs={"smarty": {"smart_dashes": False}})
    body = md.convert(m.group(2))
    words = len(re.sub(r"<[^>]+>", " ", body).split())
    return {
        "title":   str(meta["title"]),
        "date":    date,
        "updated": as_date(meta["updated"], fname) if meta.get("updated") else date,
        "slug":    slugify(meta.get("slug") or (named.group(2) if named else meta["title"])),
        "tags":    [str(t) for t in tags if str(t).strip()],
        "summary": str(meta.get("summary") or "").strip(),
        "draft":   bool(meta.get("draft")),
        "minutes": max(1, round(words / 220)),
        "body":    body,
        "source":  fname,
    }


